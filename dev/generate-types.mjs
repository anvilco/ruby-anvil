// GraphQL

const SCALARS = new Set(['String', 'ID', 'Int', 'Float', 'Boolean', 'JSON', 'Upload'])
const TIME_SCALARS = new Set(['Date'])

// How a GraphQL type lands in the DSL: a nested object gets `type:`, a list of
// them `array_of:`, the Date scalar `type: :time`, everything else stays as it
// came (enums are strings, JSON is whatever it is)
function graphqlOptions(type, namespace) {
  if (isNonNullType(type)) return graphqlOptions(type.ofType, namespace)
  if (isListType(type)) {
    const inner = graphqlOptions(type.ofType, namespace)
    return inner.type ? { arrayOf: inner.type } : {}
  }
  if (isScalarType(type)) {
    if (TIME_SCALARS.has(type.name)) return { time: true }
    if (!SCALARS.has(type.name)) throw new Error(`Unexpected scalar ${type.name}`)
    return {}
  }
  if (isEnumType(type)) return {}
  return { type: `${namespace}::${className(type.name)}` }
}

function defaultOf(fieldOrArg) {
  if (fieldOrArg.defaultValue !== undefined) return fieldOrArg.defaultValue
  const { default: def } = fieldOrArg
  if (!def) return undefined
  return def.value !== undefined ? def.value : valueFromAST(def.literal, fieldOrArg.type)
}

function describeField(field, { withDefault }) {
  const parts = [field.description?.trim()].filter(Boolean)
  const defaultValue = withDefault ? defaultOf(field) : undefined
  if (defaultValue !== undefined && defaultValue !== null) parts.push(`Defaults to \`${JSON.stringify(defaultValue)}\` when left out.`)
  return { description: parts.join('\n'), hasDefault: defaultValue !== undefined }
}

function generateGraphql(schema) {
  const roots = new Set([schema.getQueryType()?.name, schema.getMutationType()?.name])
  const types = []
  const enums = []
  for (const type of Object.values(schema.getTypeMap())) {
    if (type.name.startsWith('__') || roots.has(type.name)) continue
    if (isEnumType(type)) {
      enums.push(new EnumBuilder(type.name, type.description, type.getValues().map((v) => ({ name: v.name, description: v.description }))))
      continue
    }
    if (!isObjectType(type)) continue
    const name = className(type.name)
    const renamed = RENAMES[type.name] ? `The \`${type.name}\` type of the Anvil GraphQL schema, named \`${name}\` so it does not shadow Ruby's.` : null
    const cls = new ClassBuilder(name, { description: [type.description?.trim(), renamed].filter(Boolean).join('\n'), base: 'Base' })
    for (const field of Object.values(type.getFields())) {
      cls.attribute({
        jsonName: field.name,
        ...describeField(field, { withDefault: false }),
        ...graphqlOptions(field.type, 'Anvil::Types'),
        deprecated: field.deprecationReason,
      })
    }
    types.push(cls)
  }
  const sources = `@anvilco/types@${TYPES_VERSION} schema.graphql`
  writeRuby(path.join(OUT_DIR, 'graphql.rb'), sources, [[['Anvil', 'Types'], [...types, ...enums]]])
  return { types: types.length, enums: enums.length }
}

function generateOperations(schema) {
  const inputs = []
  for (const type of Object.values(schema.getTypeMap())) {
    if (!isInputObjectType(type) || type.name.startsWith('__')) continue
    const cls = new ClassBuilder(className(type.name), { description: type.description, base: 'Base' })
    for (const field of Object.values(type.getFields())) {
      const { description, hasDefault } = describeField(field, { withDefault: true })
      cls.attribute({
        jsonName: field.name,
        description,
        ...graphqlOptions(field.type, 'Anvil::Payloads'),
        required: isNonNullType(field.type) && !hasDefault,
        deprecated: field.deprecationReason,
      })
    }
    inputs.push(cls)
  }

  const args = []
  const names = { queries: [], mutations: [] }
  for (const [kind, rootType] of [['queries', schema.getQueryType()], ['mutations', schema.getMutationType()]]) {
    if (!rootType) continue
    for (const field of Object.values(rootType.getFields())) {
      const name = `${pascal(field.name)}Args`
      if (args.some((a) => a.name === name)) throw new Error(`${name} would be both a query and a mutation`)
      names[kind].push(field.name)
      const returns = isNonNullType(field.type) ? field.type.ofType : field.type
      const returnsName = isListType(returns) ? `[${returns.ofType.name}]` : returns.name
      const description = [`Arguments of the \`${field.name}\` ${kind === 'queries' ? 'query' : 'mutation'}, which returns \`${returnsName}\`.`, field.description?.trim()].filter(Boolean).join('\n')
      const cls = new ClassBuilder(name, { description, base: 'Anvil::Payloads::Base' })
      for (const arg of field.args) {
        const { description: argDescription, hasDefault } = describeField(arg, { withDefault: true })
        cls.attribute({
          jsonName: arg.name,
          description: argDescription,
          ...graphqlOptions(arg.type, 'Anvil::Payloads'),
          required: isNonNullType(arg.type) && !hasDefault,
          deprecated: arg.deprecationReason,
        })
      }
      args.push(cls)
    }
  }

  // Each list on its own lines, the closing bracket under its key
  const list = (key, items, last) => [
    `${INDENT}${key}: %w[`,
    ...items.map((n) => `${INDENT}${INDENT}${n}`),
    `${INDENT}].freeze${last ? '' : ','}`,
  ]
  const namesLines = [
    '# The names of every query and mutation in the Anvil GraphQL schema',
    'NAMES = {',
    ...list('queries', names.queries, false),
    ...list('mutations', names.mutations, true),
    '}.freeze',
  ]
  const namesBuilder = { lines: (indent) => namesLines.map((l) => `${indent}${l}`) }

  const sources = `@anvilco/types@${TYPES_VERSION} schema.graphql`
  writeRuby(path.join(OUT_DIR, 'operations.rb'), sources, [
    [['Anvil', 'Payloads'], inputs],
    [['Anvil', 'Operations'], [...args, namesBuilder]],
  ])
  return { inputs: inputs.length, operations: args.length }
}

