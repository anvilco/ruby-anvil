// OpenAPI

function refName(ref) {
  const match = /^#\/components\/schemas\/([A-Za-z0-9_]+)$/.exec(ref)
  if (!match) throw new Error(`Unsupported $ref ${ref}`)
  return match[1]
}

function constraints(schema) {
  const notes = []
  if (schema.minimum != null && schema.maximum != null) notes.push(`Between ${schema.minimum} and ${schema.maximum}.`)
  else if (schema.minimum != null) notes.push(`At least ${schema.minimum}.`)
  else if (schema.maximum != null) notes.push(`At most ${schema.maximum}.`)
  if (schema.default !== undefined) notes.push(`Defaults to \`${JSON.stringify(schema.default)}\` when left out.`)
  return notes
}

function describeAlternatives(alternatives, classNames) {
  const parts = alternatives.map((alt, i) => {
    if (alt.$ref) return `a ${refName(alt.$ref)}`
    if (alt.enum) return alt.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' or ')
    if (alt.type === 'object' && classNames[i]) return `a ${classNames[i]}`
    if (alt.type === 'array') return `a list of ${alt.items?.type === 'object' && classNames[i] ? classNames[i] : alt.items?.type ?? 'values'}`
    if (alt.type === 'object') return 'an object'
    return `a ${alt.type}`
  })
  return `One of: ${parts.join('; ')}.`
}

// The DSL options for an OpenAPI property, emitting nested classes into `file`
// as it goes. A nested object gets its own class named after its owner.
function restOptions(schema, owner, jsonName, file) {
  if (schema.$ref) return { type: `Anvil::Payloads::${refName(schema.$ref)}` }

  if (schema.oneOf) {
    const classNames = []
    let count = 0
    for (const alt of schema.oneOf) {
      const objectSchema = alt.type === 'object' && alt.properties ? alt : alt.type === 'array' && alt.items?.type === 'object' && alt.items.properties ? alt.items : null
      if (objectSchema) {
        count += 1
        const name = `${owner.name}${pascal(alt.type === 'array' ? singular(jsonName) : jsonName)}${count > 1 ? count : ''}`
        buildRestClass(name, objectSchema, file)
        classNames.push(name)
      } else {
        classNames.push(null)
      }
    }
    return { note: describeAlternatives(schema.oneOf, classNames) }
  }

  switch (schema.type) {
    case 'string':
      if (schema.enum && schema.enum.every((v) => typeof v === 'string')) {
        owner.enumeration(jsonName, schema.enum)
        return { note: `See \`${constant(jsonName)}_VALUES\`.` }
      }
      return {}
    case 'array': {
      const items = schema.items ?? {}
      if (items.oneOf) {
        const classNames = []
        let count = 0
        for (const alt of items.oneOf) {
          if (alt.type === 'object' && alt.properties) {
            count += 1
            const name = `${owner.name}${pascal(singular(jsonName))}${count > 1 ? count : ''}`
            buildRestClass(name, alt, file)
            classNames.push(name)
          } else {
            classNames.push(null)
          }
        }
        return { note: `Each item is ${describeAlternatives(items.oneOf, classNames).replace(/^One of: /, 'one of: ')}` }
      }
      const inner = restOptions(items, owner, singular(jsonName), file)
      return inner.type ? { arrayOf: inner.type, note: inner.note } : { note: inner.note }
    }
    case 'object':
    default:
      if (schema.properties) {
        const name = `${owner.name}${pascal(jsonName)}`
        buildRestClass(name, schema, file)
        return { type: `Anvil::Payloads::${name}` }
      }
      return {}
  }
}

function buildRestClass(name, schema, file) {
  if (file.some((cls) => cls.name === name)) throw new Error(`${name} is generated twice`)
  const cls = new ClassBuilder(name, { description: schema.description, base: 'Base' })
  file.push(cls)
  const required = new Set(schema.required ?? [])
  for (const [jsonName, propSchema] of Object.entries(schema.properties ?? {})) {
    const { type, arrayOf, note } = restOptions(propSchema, cls, jsonName, file)
    const description = [propSchema.description?.trim(), note, ...constraints(propSchema)].filter(Boolean).join('\n')
    cls.attribute({ jsonName, description, type, arrayOf, required: required.has(jsonName) })
  }
  return cls
}

function generateRest(spec) {
  const classes = []
  for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
    buildRestClass(name, schema, classes)
  }
  const sources = `@anvilco/types@${TYPES_VERSION} openapi.json`
  writeRuby(path.join(OUT_DIR, 'rest.rb'), sources, [[['Anvil', 'Payloads'], classes]])
  return classes.length
}

// ---------------------------------------------------------------------------

function main() {
  const schema = buildSchema(readFileSync(SCHEMA_PATH, 'utf8'))
  const spec = JSON.parse(readFileSync(OPENAPI_PATH, 'utf8'))

  const rest = generateRest(spec)
  const { types, enums } = generateGraphql(schema)
  const { inputs, operations } = generateOperations(schema)

  console.log(
    `Wrote ${types} GraphQL types, ${enums} enums, ${inputs} input types, ${operations} operation argument types and ${rest} REST types from @anvilco/types@${TYPES_VERSION} to ${path.relative(root, OUT_DIR)}`,
  )
}

main()
