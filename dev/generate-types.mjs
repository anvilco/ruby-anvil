// Generates lib/anvil/types/generated from the API specs that ship with the
// @anvilco/types dependency in dev/ (see dev/fetch-schema.sh): graphql.rb
// from schema.graphql (object types, enums), operations.rb from the same
// (input types, the arguments of every query and mutation, NAMES), rest.rb
// from openapi.json (request bodies). Everything lands in the client's own
// attribute DSL; CONTRIBUTING.md's Types section says why, and how the
// hand-written files build on the output.
//
// Reads the installed package only, so this runs offline.
//
// Usage: cd dev && npm ci && npm run generate
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { buildSchema, isEnumType, isInputObjectType, isListType, isNonNullType, isObjectType, isScalarType, valueFromAST } from 'graphql'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const SCHEMA_PATH = require.resolve('@anvilco/types/schema.graphql')
const OPENAPI_PATH = require.resolve('@anvilco/types/openapi.json')
const TYPES_VERSION = JSON.parse(readFileSync(path.join(SCHEMA_PATH, '..', '..', 'package.json'), 'utf8')).version
const OUT_DIR = path.join(root, 'lib', 'anvil', 'types', 'generated')

// GraphQL type names that would shadow a Ruby core constant from inside the
// Anvil::Types namespace, where every generated class lives. File is the one
// the schema has today; a spec fails when it gains another.
export const RENAMES = {
  File: 'AnvilFile',
}

// Attribute names Ruby or the DSL's base classes already own. A field with one
// of these names gets a `_value` suffix and keeps its API name as the key.
const RESERVED = new Set([
  // Ruby keywords
  'alias', 'and', 'begin', 'break', 'case', 'class', 'def', 'defined?', 'do', 'else', 'elsif', 'end',
  'ensure', 'false', 'for', 'if', 'in', 'module', 'next', 'nil', 'not', 'or', 'redo', 'rescue', 'retry',
  'return', 'self', 'super', 'then', 'true', 'undef', 'unless', 'until', 'when', 'while', 'yield',
  // Object and the base classes
  'raw', 'extra', 'to_h', 'to_hash', 'hash', 'inspect', 'freeze', 'send', 'object_id', 'method', 'methods',
  'display', 'dup', 'clone', 'tap', 'then', 'instance_variables',
])

// ---------------------------------------------------------------------------
// Naming

// Splits camelCase into words, keeping acronyms and their plurals whole:
// webhookURL -> [webhook, URL], mergePDFs -> [merge, PDFs], base64File -> [base64, File]
function words(name) {
  return name
    .replace(/([A-Z]+)([A-Z][a-z]{2,})/g, '$1_$2')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .split(/[_\-\s]+/)
    .filter(Boolean)
}

function snake(name) {
  return words(name).map((w) => w.toLowerCase()).join('_')
}

function pascal(name) {
  return words(name).map((w) => w[0].toUpperCase() + w.slice(1).toLowerCase()).join('')
}

function constant(name) {
  return words(name).map((w) => w.toUpperCase()).join('_')
}

// What Anvil::Types::Attributes.camelize would make of a snake_case name. When
// that differs from the API's name (webhookURL, mergePDFs), the attribute
// carries `key:` so the DSL still reads and writes the API's spelling.
function dslCamelize(snakeName) {
  const [head, ...rest] = snakeName.split('_')
  return [head, ...rest.map((w) => w[0].toUpperCase() + w.slice(1))].join('')
}

function singular(name) {
  if (name.endsWith('ies')) return name.slice(0, -3) + 'y'
  if (name.endsWith('s') && !name.endsWith('ss')) return name.slice(0, -1)
  return name
}

function className(name) {
  return RENAMES[name] ?? name
}

// ---------------------------------------------------------------------------
// Emitting Ruby

const INDENT = '  '

function rubyString(value) {
  return JSON.stringify(String(value))
}

// Wrapped so the generated files pass the repo's line length as written
const LINE_LENGTH = 120

function comment(text, indent) {
  if (!text) return []
  const width = LINE_LENGTH - indent.length - 2
  const out = []
  for (const paragraph of text.trim().split('\n')) {
    let line = ''
    for (const word of paragraph.trim().split(/\s+/)) {
      if (line && line.length + 1 + word.length > width) {
        out.push(`${indent}# ${line}`)
        line = word
      } else {
        line = line ? `${line} ${word}` : word
      }
    }
    out.push(line ? `${indent}# ${line}` : `${indent}#`)
  }
  return out
}

function header(sources) {
  return [
    '# frozen_string_literal: true',
    '',
    `# Generated by dev/generate-types.mjs from ${sources}. Do not edit by hand:`,
    '# run `npm run generate` in dev/ to regenerate.',
    '',
  ]
}

// One generated class: its attributes, in the DSL
class ClassBuilder {
  constructor(name, { description, base } = {}) {
    this.name = name
    this.description = description
    this.base = base
    this.attributes = []
    this.enumValues = []
    this.required = []
    this.taken = new Set()
  }

  attribute({ jsonName, description, type, arrayOf, time, required, deprecated }) {
    let name = snake(jsonName)
    if (RESERVED.has(name)) name = `${name}_value`
    if (this.taken.has(name)) throw new Error(`${this.name} would have two attributes named ${name}`)
    this.taken.add(name)
    const options = []
    if (dslCamelize(name) !== jsonName) options.push(`key: ${rubyString(jsonName)}`)
    if (time) options.push('type: :time')
    else if (type) options.push(`type: ${type}`)
    if (arrayOf) options.push(`array_of: ${arrayOf}`)
    this.attributes.push({ name, options, description, deprecated })
    if (required) this.required.push(jsonName)
  }

  // The values the API documents for a string attribute, as a constant beside it
  enumeration(jsonName, values) {
    const name = `${constant(jsonName)}_VALUES`
    if (this.enumValues.some((e) => e.name === name)) return
    this.enumValues.push({ name, jsonName, values })
  }

  lines(indent) {
    const out = []
    out.push(...comment(this.description, indent))
    out.push(`${indent}class ${this.name} < ${this.base}`)
    const inner = indent + INDENT
    const sections = []
    if (this.required.length) {
      sections.push([`${inner}# What the API requires in this payload`, `${inner}REQUIRED = %w[${this.required.join(' ')}].freeze`])
    }
    for (const e of this.enumValues) {
      sections.push([`${inner}# The values the API documents for \`${e.jsonName}\``, `${inner}${e.name} = %w[${e.values.join(' ')}].freeze`])
    }
    for (const attr of this.attributes) {
      const block = []
      block.push(...comment(attr.description, inner))
      if (attr.deprecated) block.push(`${inner}# @deprecated ${attr.deprecated.trim().replace(/\n+/g, ' ')}`)
      const options = attr.options.length ? `, ${attr.options.join(', ')}` : ''
      block.push(`${inner}attribute :${attr.name}${options}`)
      sections.push(block)
    }
    if (sections.length === 0) {
      out.push(`${inner}# ${this.name.endsWith('Args') ? 'This operation takes no arguments' : 'The API gives this type no fields a client can read'}`)
    }
    sections.forEach((block, i) => {
      // A blank line between documented attributes keeps them readable; bare
      // attribute lines stack
      if (i > 0 && (block.length > 1 || sections[i - 1].length > 1)) out.push('')
      out.push(...block)
    })
    out.push(`${indent}end`)
    return out
  }
}

// A module of string constants for a GraphQL enum
class EnumBuilder {
  constructor(name, description, values) {
    this.name = name
    this.description = description
    this.values = values
  }

  lines(indent) {
    const out = []
    out.push(...comment(this.description, indent))
    out.push(`${indent}module ${this.name}`)
    const inner = indent + INDENT
    for (const value of this.values) {
      out.push(...comment(value.description, inner))
      out.push(`${inner}${constant(value.name)} = ${rubyString(value.name)}`)
    }
    out.push('', `${inner}VALUES = [${this.values.map((v) => constant(v.name)).join(', ')}].freeze`)
    out.push(`${indent}end`)
    return out
  }
}

// Writes one file: a nesting of modules, each holding a list of builders.
// Classes are declared empty first and filled in afterwards, so an attribute
// can name a class that is defined later in the file.
function writeRuby(file, sources, modules) {
  const lines = header(sources)
  const stub = []
  const body = []
  for (const [modulePath, builders] of modules) {
    const open = modulePath.map((m, i) => `${INDENT.repeat(i)}module ${m}`)
    const close = modulePath.map((_, i) => `${INDENT.repeat(modulePath.length - 1 - i)}end`)
    const indent = INDENT.repeat(modulePath.length)
    const classes = builders.filter((b) => b instanceof ClassBuilder)
    if (classes.length) {
      stub.push(...open)
      stub.push(`${indent}# Declared empty first, so an attribute below can name a class defined later in the file`)
      for (const b of classes) stub.push(`${indent}class ${b.name} < ${b.base}; end`)
      stub.push(...close, '')
    }
    body.push(...open)
    builders.forEach((b, i) => {
      if (i > 0) body.push('')
      // A reopening carries no superclass: it was declared above
      body.push(...(b instanceof ClassBuilder ? reopen(b, indent) : b.lines(indent)))
    })
    body.push(...close, '')
  }
  lines.push(...stub, ...body)
  mkdirSync(path.dirname(file), { recursive: true })
  writeFileSync(file, lines.join('\n').replace(/\n{3,}/g, '\n\n'))
}

function reopen(builder, indent) {
  const all = builder.lines(indent)
  const at = all.findIndex((l) => l.trimStart().startsWith('class '))
  all[at] = all[at].replace(/ < .*$/, '')
  return all
}

